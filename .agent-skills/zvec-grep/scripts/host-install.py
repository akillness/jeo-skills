#!/usr/bin/env python3
"""Preview additive host hook configuration; never write to the selected home."""
import argparse
import json
from pathlib import Path
import shlex
import os
import tempfile
import sys

BRIDGE = Path(__file__).resolve().with_name('host-events.py')


def extension_source(warnings_dir, daemon_home):
    bridge = json.dumps(str(BRIDGE))
    warnings = json.dumps(str(warnings_dir))
    daemon = json.dumps(str(daemon_home))
    return f'''// zvec-grep response hooks; generated by host-install.py
import {{ spawn }} from "node:child_process";
export default function (pi) {{
  const invoke = (phase, ctx) => new Promise((resolve) => {{
    const child = spawn("python3", [{bridge}, phase], {{ stdio: ["pipe", "ignore", "ignore"], env: {{ ...process.env, ZVEC_GREP_MANAGED_WARNINGS_DIR: {warnings}, ZVEC_GREP_HOME: {daemon} }} }});
    child.on("error", resolve);
    child.on("close", resolve);
    child.stdin.on("error", () => {{}});
    child.stdin.end(JSON.stringify({{ cwd: ctx.cwd, session_id: ctx.sessionManager.getSessionId() }}));
  }});
  pi.on("before_agent_start", async (_event, ctx) => {{ await invoke("start", ctx); }});
  pi.on("agent_end", async (_event, ctx) => {{ await invoke("end", ctx); }});
}}
'''


def opencode_plugin_source(warnings_dir, daemon_home):
    bridge = json.dumps(str(BRIDGE))
    warnings = json.dumps(str(warnings_dir))
    daemon = json.dumps(str(daemon_home))
    return f'''// zvec-grep response hooks; generated by host-install.py
import {{ spawn }} from "node:child_process";
const invoke = (phase, cwd, sessionId) => new Promise((resolve) => {{
  const child = spawn("python3", [{bridge}, phase], {{ stdio: ["pipe", "ignore", "ignore"], env: {{ ...process.env, ZVEC_GREP_MANAGED_WARNINGS_DIR: {warnings}, ZVEC_GREP_HOME: {daemon} }} }});
  child.on("error", resolve);
  child.on("close", resolve);
  child.stdin.on("error", () => {{}});
  child.stdin.end(JSON.stringify({{ cwd: cwd || process.cwd(), session_id: sessionId || "opencode" }}));
}});
export default {{
  id: "zvec-grep-response",
  setup: async (ctx) => {{
    if (!ctx || typeof ctx.session?.hook !== "function") return;
    await ctx.session.hook("prompt", async (input) => {{
      await invoke("start", ctx.cwd || process.cwd(), input?.sessionID || "opencode");
    }});
    if (typeof ctx.session?.on === "function") {{
      ctx.session.on("idle", async (input) => {{
        await invoke("end", ctx.cwd || process.cwd(), input?.sessionID || "opencode");
      }});
    }}
  }},
}};
'''


def merged_agy_config(path, warnings_dir, daemon_home):
    if path.exists():
        data = json.loads(path.read_text(encoding='utf-8'))
        if not isinstance(data, dict):
            raise ValueError(f'{path}: settings must be a JSON object')
    else:
        data = {}
    bridge = shlex.quote(str(BRIDGE))
    command = f'test ! -f {bridge} || ZVEC_GREP_MANAGED_WARNINGS_DIR={shlex.quote(str(warnings_dir))} ZVEC_GREP_HOME={shlex.quote(str(daemon_home))} python3 {bridge} start || true ; printf \'{{}}\''
    entry = {'PreInvocation': [{'type': 'command', 'command': command}]}
    existing = data.get('zvec-grep-response')
    if existing is not None and existing != entry:
        raise ValueError(f'{path}: existing zvec-grep-response hook uses a different warning directory or daemon home')
    data['zvec-grep-response'] = entry
    return data


def merged_config(path, events, warnings_dir, daemon_home, codex=False):
    if path.exists():
        data = json.loads(path.read_text(encoding='utf-8'))
        if not isinstance(data, dict):
            raise ValueError(f'{path}: settings must be a JSON object')
    else:
        data = {}
    hooks = data.setdefault('hooks', {})
    if not isinstance(hooks, dict):
        raise ValueError(f'{path}: hooks must be a JSON object')
    for event, phase in events:
        bridge = shlex.quote(str(BRIDGE))
        command = f'test ! -f {bridge} || ZVEC_GREP_MANAGED_WARNINGS_DIR={shlex.quote(str(warnings_dir))} ZVEC_GREP_HOME={shlex.quote(str(daemon_home))} python3 {bridge} {phase} || true'
        if codex:
            command += " ; printf '{}'"
        entries = hooks.setdefault(event, [])
        if not isinstance(entries, list):
            raise ValueError(f'{path}: {event} hooks must be an array')
        entry = {'hooks': [{'type': 'command', 'command': command}]}
        for existing in list(entries):
            if not isinstance(existing, dict) or set(existing) != {'hooks'} or not isinstance(existing['hooks'], list) or len(existing['hooks']) != 1:
                continue
            hook = existing['hooks'][0]
            if not isinstance(hook, dict) or set(hook) != {'type', 'command'} or hook['type'] != 'command' or not isinstance(hook['command'], str):
                continue
            if codex and hook['command'] == command.removesuffix(" ; printf '{}'"):
                if entry in entries:
                    entries.remove(existing)
                else:
                    hook['command'] = command
                continue
            try:
                tokens = shlex.split(hook['command'])
            except ValueError:
                continue
            if codex and tokens[-3:] == [';', 'printf', '{}']:
                tokens = tokens[:-3]
            if (len(tokens) in (11, 12) and tokens[:4] == ['test', '!', '-f', str(BRIDGE)]
                    and tokens[4] == '||' and tokens[5].startswith('ZVEC_GREP_MANAGED_WARNINGS_DIR=')
                    and (len(tokens) == 11 or tokens[6].startswith('ZVEC_GREP_HOME='))
                    and tokens[-5:] == ['python3', str(BRIDGE), phase, '||', 'true'] and existing != entry):
                raise ValueError(f'{path}: existing managed hook uses a different warning directory or daemon home')
        legacy = [
            {'hooks': [{'type': 'command', 'command': f'python3 {bridge} {phase}'}]},
            {'hooks': [{'type': 'command', 'command': f'test ! -f {bridge} || python3 {bridge} {phase} || true'}]},
        ]
        for old in legacy:
            while old in entries:
                if entry in entries:
                    entries.remove(old)
                else:
                    entries[entries.index(old)] = entry
        if entry not in entries:
            entries.append(entry)
    return data


SUPPORTED_TARGETS = ['claude', 'gemini', 'codex', 'pi', 'omp', 'jeopi', 'jeo', 'gjc', 'opencode', 'agy']
PI_EXTENSION_HOSTS = [
    ('pi', '.pi/agent/extensions'),
    ('omp', '.omp/agent/extensions'),
    ('jeopi', '.jeopi/agent/extensions'),
    ('jeo', '.jeo/agent/extensions'),
    ('gjc', '.gjc/agent/extensions'),
]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--home', type=Path, default=Path.home())
    parser.add_argument('--target', action='append', choices=SUPPORTED_TARGETS)
    parser.add_argument('--warnings-dir', type=Path, help='absolute warning directory shared with the managed daemon')
    parser.add_argument('--daemon-home', type=Path, help='absolute home directory of the managed daemon')
    parser.add_argument('--apply', action='store_true', help='write only explicitly selected targets')
    args = parser.parse_args()
    if args.apply and not args.target:
        parser.error('--apply requires at least one --target')
    selected = set(args.target or SUPPORTED_TARGETS)
    home = args.home.expanduser().resolve()
    warnings_dir = args.warnings_dir or home / '.local/state/zvec-grep/warnings'
    if not warnings_dir.is_absolute():
        parser.error('--warnings-dir must be absolute')
    warnings_dir = Path(os.path.abspath(warnings_dir))
    daemon_home = args.daemon_home or home / '.zvec-grep'
    if not daemon_home.is_absolute():
        parser.error('--daemon-home must be absolute')
    daemon_home = Path(os.path.abspath(daemon_home))
    previews = []
    try:
        for host, relative, events in [
            ('claude', '.claude/settings.json', [('UserPromptSubmit', 'start'), ('Stop', 'end')]),
            ('gemini', '.gemini/settings.json', [('BeforeAgent', 'start'), ('AfterAgent', 'end')]),
            ('codex', '.codex/hooks.json', [('UserPromptSubmit', 'start'), ('Stop', 'end')]),
        ]:
            if host not in selected:
                continue
            path = home / relative
            content = merged_config(path, events, warnings_dir, daemon_home, codex=host == 'codex')
            previews.append({'host': host, 'path': str(path), 'content': content,
                             'hook_events': [event for event, _ in events],
                             'original': path.read_bytes() if path.exists() else None})
        if 'agy' in selected:
            path = home / '.gemini/config/hooks.json'
            content = merged_agy_config(path, warnings_dir, daemon_home)
            previews.append({'host': 'agy', 'path': str(path), 'content': content,
                             'hook_events': ['PreInvocation'],
                             'original': path.read_bytes() if path.exists() else None})
        for host, relative in PI_EXTENSION_HOSTS:
            if host not in selected:
                continue
            path = home / relative / 'zvec-grep-response.ts'
            if path.exists() and path.read_text(encoding='utf-8') != extension_source(warnings_dir, daemon_home):
                raise ValueError(f'{path}: existing extension differs; refusing to overwrite')
            previews.append({'host': host, 'path': str(path), 'content': extension_source(warnings_dir, daemon_home),
                             'original': path.read_bytes() if path.exists() else None})
        if 'opencode' in selected:
            path = home / '.config/opencode/plugins/zvec-grep-response.js'
            if path.exists() and path.read_text(encoding='utf-8') != opencode_plugin_source(warnings_dir, daemon_home):
                raise ValueError(f'{path}: existing plugin differs; refusing to overwrite')
            previews.append({'host': 'opencode', 'path': str(path), 'content': opencode_plugin_source(warnings_dir, daemon_home),
                             'original': path.read_bytes() if path.exists() else None})
        if args.apply:
            for change in previews:
                path = Path(change['path'])
                if path.is_symlink():
                    path = path.resolve(strict=True)
                path.parent.mkdir(parents=True, exist_ok=True)
                text = change['content'] if isinstance(change['content'], str) else json.dumps(change['content'], indent=2) + '\n'
                original = change.get('original')
                if original is not None and ((isinstance(change['content'], str) and original.decode('utf-8') == text)
                                             or (not isinstance(change['content'], str) and json.loads(original) == change['content'])):
                    continue
                fd, name = tempfile.mkstemp(prefix='.zvec-hook-', dir=path.parent)
                try:
                    if path.exists():
                        os.fchmod(fd, path.stat().st_mode & 0o777)
                    with os.fdopen(fd, 'w', encoding='utf-8') as stream:
                        stream.write(text)
                    if 'original' in change and (path.read_bytes() if path.exists() else None) != original:
                        raise ValueError(f'{path}: settings changed concurrently')
                    os.replace(name, path)
                finally:
                    Path(name).unlink(missing_ok=True)
    except (OSError, ValueError) as exc:
        print(str(exc), file=sys.stderr)
        return 1
    summary = [{'host': change['host'], 'path': change['path'],
                **({'hook_events': change['hook_events']} if 'hook_events' in change else {})}
               for change in previews]
    print(json.dumps({'preview_only': not args.apply, 'changes': summary,
                      'unsupported_or_unverified': ['qwen', 'standalone cursor', 'windsurf', 'copilot', 'aside']}, indent=2))
    return 0


if __name__ == '__main__':
    sys.exit(main())
