let pageLocale: UpdateLocale | null = null;

/** The closest of the twenty to a BCP 47 tag ("zh-Hant-TW", "pt-PT", "nb"...), or null. */
export function matchUpdateLocale(tag: string | null | undefined): UpdateLocale | null {
  const value = String(tag ?? "").trim().replace(/_/g, "-").toLowerCase();
  if (!value) return null;
  const exact = UPDATE_LOCALES.find((locale) => locale.toLowerCase() === value);
  if (exact) return exact;
  const [language, ...rest] = value.split("-");
  if (language === "zh") return rest.some((part) => ["hant", "tw", "hk", "mo"].includes(part)) ? "zh-TW" : "zh";
  if (language === "en") return rest.some((part) => ["gb", "uk", "ie", "au", "nz", "in", "za"].includes(part)) ? "en-GB" : "en";
  if (language === "es") return rest.length && !rest.includes("es") ? "es-419" : "es";
  if (language === "pt") return "pt-BR";
  if (language === "nb" || language === "nn" || language === "no") return "no";
  return UPDATE_LOCALES.find((locale) => locale === language) ?? null;
}

/** The language the app's pages show (Settings tells it). */
export function setUpdateLocale(tag: string | null | undefined): void {
  const matched = matchUpdateLocale(tag);
  if (matched) pageLocale = matched;
}

export function updateLocale(): UpdateLocale {
  if (pageLocale) return pageLocale;
  let preferred: string[] = [];
  try {
    preferred = app.getPreferredSystemLanguages();
  } catch {
    preferred = [];
  }
  for (const tag of [...preferred, app.getLocale()]) {
    const matched = matchUpdateLocale(tag);
    if (matched) return matched;
  }
  return "en";
}

/** One string, its {placeholders} filled. */
export function ut(key: Key, values: Record<string, string | number> = {}, locale: UpdateLocale = updateLocale()): string {
  const template = TEXT[locale]?.[key] ?? en[key];
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => (name in values ? String(values[name]) : whole));
}

