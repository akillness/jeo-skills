// Writes THIRD_PARTY_NOTICES.md: every npm package the editors ship (the
// production dependency tree of the workspace packages, after npm install),
// with its license and copyright text, then the bundled runtimes and fonts
// (apps/playground/public/licenses and the license files beside the fonts).
//
//   node scripts/third-party-notices.mjs [--check]
//
// --check fails when a package's license is not one the AGPL can carry.

import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const COMPATIBLE = /^\(?(MIT|ISC|BSD|Apache-2\.0|MPL-2\.0|0BSD|Unlicense|CC0|CC-BY-4\.0|Zlib|BlueOak|Python|OFL|MIT-0|LGPL|AGPL|GPL-3|WTFPL|Artistic-2)/i;

function npmTree() {
  try {
    return execFileSync("npm", ["ls", "--all", "--omit=dev", "--json", "--workspaces"], { cwd: ROOT, encoding: "utf8", maxBuffer: 256 * 1024 * 1024, stdio: ["ignore", "pipe", "ignore"] });
  } catch (error) {
    // npm ls exits 1 on a peer-range complaint; its JSON is still complete
    if (error.stdout) return error.stdout;
    throw error;
  }
}
const tree = JSON.parse(npmTree());
const packages = new Map();
function walk(node) {
  for (const [name, child] of Object.entries(node.dependencies ?? {})) {
    if (name.startsWith("@mrnote/") || !child.version) {
      walk(child);
      continue;
    }
    const key = `${name}@${child.version}`;
    if (packages.has(key)) continue;
    packages.set(key, { name, version: child.version, path: child.path ?? join(ROOT, "node_modules", name) });
    walk(child);
  }
}
walk(tree);

function licenseText(dir) {
  if (!existsSync(dir)) return "";
  const file = readdirSync(dir).find((name) => /^(LICEN[CS]E|COPYING|NOTICE)(\.|-|$)/i.test(name));
  return file ? readFileSync(join(dir, file), "utf8").trim() : "";
}

const rows = [];
const incompatible = [];
for (const entry of [...packages.values()].sort((a, b) => a.name.localeCompare(b.name))) {
  let manifest = {};
  try {
    manifest = JSON.parse(readFileSync(join(entry.path, "package.json"), "utf8"));
  } catch {
    // a package npm ls lists but did not install (an optional one)
    continue;
  }
  let license = typeof manifest.license === "string" ? manifest.license : manifest.license?.type ?? (manifest.licenses ?? []).map((item) => item.type).join(" OR ");
  const text = licenseText(entry.path);
  // no license field: read it from the license text
  if (!license && /Redistribution and use in source and binary forms/.test(text)) license = "BSD (from LICENSE)";
  else if (!license && /Permission is hereby granted, free of charge/.test(text)) license = "MIT (from LICENSE)";
  if (!COMPATIBLE.test(license || "")) incompatible.push(`${entry.name}@${entry.version} (${license || "none"})`);
  rows.push({ ...entry, license: license || "UNKNOWN", text, homepage: manifest.homepage ?? manifest.repository?.url ?? manifest.repository ?? "" });
}

const out = [
  "# Third-party notices",
  "",
  "The MR Note editors include the following third-party software. Each is used under its own license, reproduced below.",
  "This file is generated by `npm run notices` (scripts/third-party-notices.mjs).",
  "",
  "## npm packages",
  "",
  "| Package | Version | License |",
  "|---|---|---|",
  ...rows.map((row) => `| ${row.name} | ${row.version} | ${row.license} |`),
  "",
];
const publicLicenses = join(ROOT, "apps/playground/public/licenses");
if (existsSync(publicLicenses)) {
  out.push("## Bundled runtimes and assets", "", "The playground serves these files as they are; their notices are in `apps/playground/public/licenses/`:", "");
  for (const name of readdirSync(publicLicenses).sort()) out.push(`- ${name}`);
  out.push("");
}
const fonts = [];
(function findFontLicenses(dir) {
  if (!existsSync(dir)) return;
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) findFontLicenses(path);
    else if (/^(OFL|LICENSE)/i.test(name) && /fonts/.test(path)) fonts.push(relative(ROOT, path));
  }
})(join(ROOT, "apps/playground/public/fonts"));
(function findFontLicenses(dir) {
  if (!existsSync(dir)) return;
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) findFontLicenses(path);
    else if (/^(OFL|LICENSE)/i.test(name) && /fonts/.test(path)) fonts.push(relative(ROOT, path));
  }
})(join(ROOT, "packages/core/src/web/public/fonts"));
if (fonts.length) {
  out.push("## Fonts", "", "Fonts are under the SIL Open Font License 1.1 (or the license named in the file beside them):", "", ...fonts.sort().map((path) => `- ${path}`), "");
}
// Data from the Office Open XML standard's electronic annexes (ECMA-376
// Part 1, 5th edition), which a conforming product may implement, and the
// Apache POI copies of them it was read from.
const STANDARD_DATA = [
  ["packages/core/src/web/lib/office-text-warp.shared.json", "presetTextWarpDefinitions.xml (OfficeOpenXML-DrawingMLGeometries.zip)"],
  ["packages/core/src/web/lib/office-preset-adjust-handles.generated.ts", "presetShapeDefinitions.xml (OfficeOpenXML-DrawingMLGeometries.zip)"],
  ["packages/core/src/web/lib/presentation-default-preset-programs.generated.ts", "presetShapeDefinitions.xml (OfficeOpenXML-DrawingMLGeometries.zip)"],
  ["packages/slides/src/web/lib/presentation-action-button-paths.ts", "presetShapeDefinitions.xml (OfficeOpenXML-DrawingMLGeometries.zip)"],
  ["packages/core/src/web/lib/presentation-shapes.ts", "presetShapeDefinitions.xml (OfficeOpenXML-DrawingMLGeometries.zip)"],
  ["packages/core/src/web/lib/spreadsheet/table-style-recipes.ts", "presetTableStyles.xml (OfficeOpenXML-SpreadsheetMLStyles.zip)"],
  ["packages/core/src/web/lib/spreadsheet/pivot-style-recipes.ts", "presetTableStyles.xml (OfficeOpenXML-SpreadsheetMLStyles.zip)"],
].filter(([path]) => existsSync(join(ROOT, path)));
if (STANDARD_DATA.length) {
  out.push(
    "## Standards data",
    "",
    "These files hold data from the electronic annexes of ECMA-376 Part 1, Office Open XML File Formats, 5th edition (December 2016), © Ecma International 2016, as distributed in Apache POI (Apache License 2.0):",
    "",
    ...STANDARD_DATA.map(([path, annex]) => `- \`${path}\`: ${annex}`),
    "",
    "### ECMA-376 copyright notice",
    "",
    "```",
    readFileSync(join(ROOT, "scripts/notices/ecma-376-copyright.txt"), "utf8").trim(),
    "```",
    "",
    "### Apache POI NOTICE",
    "",
    "```",
    readFileSync(join(ROOT, "scripts/notices/apache-poi-NOTICE.txt"), "utf8").trim(),
    "```",
    "",
  );
}
out.push("## License texts", "");
for (const row of rows) {
  if (!row.text) continue;
  out.push(`### ${row.name}@${row.version}`, "", "```", row.text, "```", "");
}
writeFileSync(join(ROOT, "THIRD_PARTY_NOTICES.md"), `${out.join("\n")}\n`);
console.log(`THIRD_PARTY_NOTICES.md: ${rows.length} packages, ${fonts.length} font licenses`);
if (incompatible.length) {
  console.log(`licenses to review: ${incompatible.join(", ")}`);
  if (process.argv.includes("--check")) process.exit(1);
}
