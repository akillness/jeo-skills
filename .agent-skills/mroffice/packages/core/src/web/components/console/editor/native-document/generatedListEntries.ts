/**
 * Entries a References command has just generated for a table of contents or
 * a table of figures (Insert, Update Table, the dialog's OK).
 *
 * They are read from the pages as they stand BEFORE the table is laid out
 * with them, and the table itself takes room: a table that adds two pages
 * says every page two short. Word reads the page numbers after its layout
 * (measured in Word 16.86: a 120-entry table inserted at the start of a
 * 14-page document makes it 18 pages and shows every heading's real page at
 * once; Update Field afterwards changes nothing). The page-number settle
 * (generatedListPageNumbers) does the same once the page ledger has laid the
 * table out, and knows which tables to look at by the identity of the
 * entries those commands made. Entries that came any other way (an opened
 * document, a paste, an undo, a collaborator) are never marked, so their
 * numbers stay as their author or Word last updated them.
 */
const freshEntries = new WeakSet<object>();

/** Mark `entries` as just generated by a command; returns them. */
export function markGeneratedListEntries<Entries>(entries: Entries): Entries {
  if (entries !== null && typeof entries === "object") freshEntries.add(entries);
  return entries;
}

export function isFreshGeneratedListEntries(entries: unknown): boolean {
  return entries !== null && typeof entries === "object" && freshEntries.has(entries);
}

/** The entries' page numbers have been settled (or need no settling). */
export function consumeGeneratedListEntries(entries: unknown): void {
  if (entries !== null && typeof entries === "object") freshEntries.delete(entries);
}
