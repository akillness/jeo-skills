#!/usr/bin/env python3
"""Install, remove, or inspect OpenSpace prompt-time skill routing hooks.

Every supported host runs ``route_prompt.py`` once per user prompt, before the
model sees it, and passes the ranked skill note to the model as context:

  claude    ~/.claude/settings.json         UserPromptSubmit  additionalContext
  codex     ~/.codex/hooks.json             UserPromptSubmit  additionalContext (trust in /hooks)
  gemini    ~/.gemini/settings.json         BeforeAgent       additionalContext (Gemini CLI, Antigravity)
  kimi      ~/.kimi-code/config.toml        UserPromptSubmit  hook message
  jeopi, omp, pi, gjc
            ~/.<host>/agent/extensions/     before_agent_start hidden custom message
  opencode  ~/.config/opencode/plugins/     chat.message      synthetic text part

The hooks call one wrapper, ~/.agents/hooks/openspace-route.sh, which runs a
copy of the router with the OpenSpace venv's Python and exits 0 silently when
either is missing, so routing can never block a prompt. Hosts whose config
directory does not exist are skipped. Existing files keep their mode, other
hooks and keys are preserved, symlinked or non-regular configs are refused,
and every write is an atomic same-directory replace.

    route-hooks.py install [--host NAME ...] [--dry-run]
    route-hooks.py remove  [--host NAME ...] [--dry-run]
    route-hooks.py status  [--host NAME ...]

Environment: OPENSPACE_VENV (default ~/.agents/venvs/openspace), SKILLS_ROOT
(default ~/.agents/skills), OPENSPACE_ROUTE_HOOK_DIR (default ~/.agents/hooks),
KIMI_CODE_HOME, XDG_CONFIG_HOME.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import shlex
import stat
import subprocess
import sys
import tempfile
from pathlib import Path

MARKER = "@openspace-route-managed"
HOME = Path.home()
VENV = Path(os.environ.get("OPENSPACE_VENV") or HOME / ".agents/venvs/openspace").expanduser()
SKILLS_ROOT = Path(os.environ.get("SKILLS_ROOT") or HOME / ".agents/skills").expanduser()
HOOK_DIR = Path(os.environ.get("OPENSPACE_ROUTE_HOOK_DIR") or HOME / ".agents/hooks").expanduser()
WRAPPER = HOOK_DIR / "openspace-route.sh"
ROUTER = HOOK_DIR / "openspace-route.py"
ROUTER_SOURCE = Path(__file__).resolve().with_name("route_prompt.py")
XDG_CONFIG = Path(os.environ.get("XDG_CONFIG_HOME") or HOME / ".config").expanduser()
ROUTER_SIGNATURE = '"""OpenSpace prompt-time skill router.'
KIMI_HOME = Path(os.environ.get("KIMI_CODE_HOME") or HOME / ".kimi-code").expanduser()
TIMEOUT_SECONDS = 10


def command(host_arg: str) -> str:
    return f"/bin/sh {shlex.quote(str(WRAPPER))} {host_arg}"


def wrapper_text() -> str:
    python = shlex.quote(str(VENV / "bin" / "python"))
    return f"""#!/bin/sh
# {MARKER}: generated by openspace/scripts/route-hooks.py.
# Prompt-time skill routing through OpenSpace's local BM25 ranker. It fails open:
# without the venv or the router it consumes the event and prints nothing.
py={python}
router={shlex.quote(str(ROUTER))}
if [ ! -x "$py" ] || [ ! -f "$router" ]; then
  cat >/dev/null 2>&1
  exit 0
fi
OPENSPACE_HOST_SKILL_DIRS="${{OPENSPACE_HOST_SKILL_DIRS:-{SKILLS_ROOT}}}"
export OPENSPACE_HOST_SKILL_DIRS
exec "$py" -B "$router" --host "${{1:-text}}"
"""


ROUTE_FUNCTION = """function route(prompt, host) {
  return new Promise((resolve) => {
    let out = "";
    let settled = false;
    const finish = (value) => {
      if (!settled) {
        settled = true;
        resolve(value);
      }
    };
    let child;
    try {
      child = spawn("/bin/sh", [WRAPPER, host], { stdio: ["pipe", "pipe", "ignore"] });
    } catch {
      finish("");
      return;
    }
    const timer = setTimeout(() => {
      child.kill();
      finish("");
    }, TIMEOUT_MS);
    child.stdout.on("data", (chunk) => {
      out += chunk;
    });
    child.on("error", () => {
      clearTimeout(timer);
      finish("");
    });
    child.on("close", () => {
      clearTimeout(timer);
      try {
        const parsed = JSON.parse(out);
        finish(typeof parsed.context === "string" ? parsed.context : "");
      } catch {
        finish("");
      }
    });
    child.stdin.on("error", () => {});
    child.stdin.end(JSON.stringify({ prompt }));
  });
}
"""


def pi_extension_text() -> str:
    return f"""// {MARKER}: generated by openspace/scripts/route-hooks.py; remove with `route-hooks.py remove`.
// Prompt-time skill routing: OpenSpace ranks the installed skills locally (BM25, no LLM)
// before the model runs; matches reach the model as a hidden custom message.
import {{ spawn }} from "node:child_process";

const WRAPPER = {json.dumps(str(WRAPPER))};
const TIMEOUT_MS = {TIMEOUT_SECONDS * 1000};

{ROUTE_FUNCTION}
export default function (pi: any) {{
  pi.on("before_agent_start", async (event: any) => {{
    const prompt = typeof event?.prompt === "string" ? event.prompt : "";
    if (!prompt.trim()) return {{}};
    const content = await route(prompt, "pi");
    return content ? {{ message: {{ customType: "openspace-route", content, display: false }} }} : {{}};
  }});
}}
"""


def opencode_major() -> int:
    """Installed OpenCode major version; 2 when it cannot be read (the current line)."""
    try:
        out = subprocess.run(["opencode", "--version"], capture_output=True, text=True, timeout=20).stdout
        match = re.search(r"(\d+)\.\d+", out)
        return int(match.group(1)) if match else 2
    except (OSError, subprocess.SubprocessError):
        return 2


OPENCODE_V1_HOOK = """export const OpenSpaceRoute = async () => ({
  "chat.message": async (input, output) => {
    const parts = Array.isArray(output?.parts) ? output.parts : [];
    const prompt = parts
      .filter((part) => part?.type === "text" && !part.synthetic && typeof part.text === "string")
      .map((part) => part.text)
      .join("\\n")
      .trim();
    const messageID = output?.message?.id ?? input?.messageID;
    if (!prompt || !messageID) return;
    const text = await route(prompt, "opencode");
    if (!text) return;
    parts.push({
      id: `prt_${Date.now().toString(16)}${Math.random().toString(36).slice(2, 10)}`,
      sessionID: input.sessionID,
      messageID,
      type: "text",
      text,
      synthetic: true,
    });
  },
});
"""

# OpenCode 2 validates a default {id, setup} definition; session.hook("prompt") receives the
# admitted prompt with a mutable `prompt.text`, so the note is appended to the user's text.
OPENCODE_V2_HOOK = """export default {
  id: "openspace-route",
  setup: async (ctx) => {
    if (!ctx || typeof ctx.session?.hook !== "function") return;
    await ctx.session.hook("prompt", async (input) => {
      const text = input?.prompt?.text;
      if (typeof text !== "string" || !text.trim()) return;
      const note = await route(text, "opencode");
      if (note) input.prompt.text = `${text}\\n\\n${note}`;
    });
  },
};
"""


def opencode_plugin_text() -> str:
    major = opencode_major()
    return f"""// {MARKER}: generated by openspace/scripts/route-hooks.py for OpenCode {major}; remove with `route-hooks.py remove`.
// Prompt-time skill routing: OpenSpace ranks the installed skills locally (BM25, no LLM)
// before the model runs; matches reach the model with the prompt.
import {{ spawn }} from "node:child_process";

const WRAPPER = {json.dumps(str(WRAPPER))};
const TIMEOUT_MS = {TIMEOUT_SECONDS * 1000};

{ROUTE_FUNCTION}
{OPENCODE_V1_HOOK if major < 2 else OPENCODE_V2_HOOK}"""


# ---------------------------------------------------------------- file safety


def read_regular(path: Path) -> tuple[str, int] | None:
    """(text, mode) of an existing regular file, None when absent; refuses anything else."""
    try:
        info = os.lstat(path)
    except FileNotFoundError:
        return None
    if stat.S_ISLNK(info.st_mode) or not stat.S_ISREG(info.st_mode):
        raise RuntimeError(f"refusing non-regular file: {path}")
    return path.read_text(encoding="utf-8"), stat.S_IMODE(info.st_mode)


def atomic_write(path: Path, text: str, mode: int) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, name = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    temporary = Path(name)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as out:
            out.write(text)
            out.flush()
            os.fsync(out.fileno())
        os.chmod(temporary, mode)
        if path.exists() or path.is_symlink():
            info = os.lstat(path)
            if stat.S_ISLNK(info.st_mode) or not stat.S_ISREG(info.st_mode):
                raise RuntimeError(f"{path} changed type before replacement")
        os.replace(temporary, path)
    except BaseException:
        temporary.unlink(missing_ok=True)
        raise


def ours(text: str) -> bool:
    return str(WRAPPER) in text


# ---------------------------------------------------------------- host kinds


class JsonHooks:
    """Claude Code, Codex, and Gemini: hooks.<event>[] in a JSON settings file."""

    def __init__(self, name: str, path: Path, event: str, host_arg: str, gate: Path, gemini: bool = False):
        self.name, self.path, self.event, self.host_arg, self.gate, self.gemini = name, path, event, host_arg, gate, gemini

    def detected(self) -> bool:
        return self.path.exists() or self.gate.is_dir()

    def entry(self) -> dict:
        hook = {"type": "command", "command": command(self.host_arg)}
        if self.gemini:
            # Gemini hook timeouts are milliseconds; entries carry a matcher and name.
            return {"matcher": "", "hooks": [{"name": "openspace-route", **hook, "timeout": TIMEOUT_SECONDS * 1000}]}
        return {"hooks": [{**hook, "timeout": TIMEOUT_SECONDS}]}

    def load(self) -> tuple[dict, int]:
        existing = read_regular(self.path)
        if existing is None:
            return {}, 0o600
        text, mode = existing
        data = json.loads(text) if text.strip() else {}
        if not isinstance(data, dict):
            raise RuntimeError(f"unexpected JSON root in {self.path}")
        return data, mode

    def entries(self, data: dict) -> list:
        hooks = data.get("hooks", {})
        if not isinstance(hooks, dict):
            raise RuntimeError(f"unexpected 'hooks' shape in {self.path}")
        entries = hooks.get(self.event, [])
        if not isinstance(entries, list):
            raise RuntimeError(f"unexpected hooks.{self.event} shape in {self.path}")
        return entries

    def without_ours(self, entries: list) -> list:
        kept = []
        for entry in entries:
            if not isinstance(entry, dict) or not isinstance(entry.get("hooks"), list):
                kept.append(entry)
                continue
            hooks = [h for h in entry["hooks"] if not (isinstance(h, dict) and ours(str(h.get("command", ""))))]
            if hooks:
                kept.append({**entry, "hooks": hooks} if len(hooks) != len(entry["hooks"]) else entry)
        return kept

    def status(self) -> str:
        if not self.path.exists():
            return "not installed"
        data, _ = self.load()
        found = [h for e in self.entries(data) if isinstance(e, dict) for h in e.get("hooks", []) if isinstance(h, dict) and ours(str(h.get("command", "")))]
        if not found:
            return "not installed"
        return "installed" if any(h.get("command") == command(self.host_arg) for h in found) else "installed (stale command)"

    def install(self, dry: bool) -> str:
        data, mode = self.load()
        entries = self.entries(data)
        kept = self.without_ours(entries)
        wanted = kept + [self.entry()]
        if wanted == entries:
            return "unchanged"
        if dry:
            return "would install"
        data.setdefault("hooks", {})[self.event] = wanted
        atomic_write(self.path, json.dumps(data, indent=2, ensure_ascii=False) + "\n", mode)
        return "installed"

    def remove(self, dry: bool) -> str:
        if not self.path.exists():
            return "not installed"
        data, mode = self.load()
        entries = self.entries(data)
        kept = self.without_ours(entries)
        if kept == entries:
            return "not installed"
        if dry:
            return "would remove"
        if kept:
            data["hooks"][self.event] = kept
        else:
            del data["hooks"][self.event]
        atomic_write(self.path, json.dumps(data, indent=2, ensure_ascii=False) + "\n", mode)
        return "removed"

    def note(self) -> str:
        if self.name == "codex":
            return "review and trust the new UserPromptSubmit hook in Codex /hooks; Codex skips untrusted hooks"
        return ""


class KimiHooks:
    """Kimi Code: [[hooks]] array tables in config.toml; plain stdout becomes the hook message."""

    name, host_arg = "kimi", "kimi"

    def __init__(self) -> None:
        self.path = KIMI_HOME / "config.toml"

    def detected(self) -> bool:
        return self.path.exists() or KIMI_HOME.is_dir()

    def block(self) -> str:
        return (
            f"[[hooks]]\n# {MARKER}\nevent = \"UserPromptSubmit\"\n"
            f"command = {json.dumps(command(self.host_arg))}\ntimeout = {TIMEOUT_SECONDS}\n"
        )

    @staticmethod
    def chunks(text: str) -> list[str]:
        """Split at table headers so one [[hooks]] table can be dropped without parsing TOML."""
        out: list[str] = []
        for line in text.splitlines(keepends=True):
            if line.lstrip().startswith("[") or not out:
                out.append(line)
            else:
                out[-1] += line
        return out

    def without_ours(self, text: str) -> str:
        return "".join(c for c in self.chunks(text) if not (c.lstrip().startswith("[[hooks]]") and ours(c)))

    @staticmethod
    def validate(text: str) -> None:
        try:
            import tomllib
        except ModuleNotFoundError:
            return
        tomllib.loads(text)

    def status(self) -> str:
        existing = read_regular(self.path)
        if existing is None or not ours(existing[0]):
            return "not installed"
        return "installed" if self.block() in existing[0] else "installed (stale command)"

    def install(self, dry: bool) -> str:
        existing = read_regular(self.path)
        text, mode = existing if existing else ("", 0o600)
        if self.block() in text:
            return "unchanged"
        kept = self.without_ours(text)
        new = (kept.rstrip("\n") + "\n\n" if kept.strip() else "") + self.block()
        self.validate(new)
        if dry:
            return "would install"
        atomic_write(self.path, new, mode)
        return "installed"

    def remove(self, dry: bool) -> str:
        existing = read_regular(self.path)
        if existing is None or not ours(existing[0]):
            return "not installed"
        text, mode = existing
        new = self.without_ours(text).rstrip("\n") + "\n"
        self.validate(new)
        if dry:
            return "would remove"
        atomic_write(self.path, new, mode)
        return "removed"

    def note(self) -> str:
        return ""


class ManagedFile:
    """pi-family extensions and the OpenCode plugin: one generated file carrying MARKER."""

    def __init__(self, name: str, path: Path, gate: Path, render) -> None:
        self.name, self.path, self.gate, self.render = name, path, gate, render

    def detected(self) -> bool:
        return self.gate.is_dir()

    def status(self) -> str:
        existing = read_regular(self.path)
        if existing is None:
            return "not installed"
        if MARKER not in existing[0]:
            return f"foreign file at {self.path}"
        return "installed" if existing[0] == self.render() else "installed (stale)"

    def install(self, dry: bool) -> str:
        existing = read_regular(self.path)
        if existing is not None and MARKER not in existing[0]:
            raise RuntimeError(f"refusing to replace a file this tool did not write: {self.path}")
        if existing is not None and existing[0] == self.render():
            return "unchanged"
        if dry:
            return "would install"
        atomic_write(self.path, self.render(), 0o644)
        return "installed"

    def remove(self, dry: bool) -> str:
        existing = read_regular(self.path)
        if existing is None or MARKER not in existing[0]:
            return "not installed"
        if dry:
            return "would remove"
        self.path.unlink()
        return "removed"

    def note(self) -> str:
        return "takes effect in new sessions"


def hosts() -> dict:
    found = {
        "claude": JsonHooks("claude", HOME / ".claude/settings.json", "UserPromptSubmit", "claude", HOME / ".claude"),
        "codex": JsonHooks("codex", HOME / ".codex/hooks.json", "UserPromptSubmit", "codex", HOME / ".codex"),
        "gemini": JsonHooks("gemini", HOME / ".gemini/settings.json", "BeforeAgent", "gemini", HOME / ".gemini", gemini=True),
        "kimi": KimiHooks(),
    }
    for name in ("jeopi", "omp", "pi", "gjc"):
        agent = HOME / f".{name}" / "agent"
        found[name] = ManagedFile(name, agent / "extensions" / "openspace-route.ts", agent, pi_extension_text)
    opencode = XDG_CONFIG / "opencode"
    found["opencode"] = ManagedFile("opencode", opencode / "plugins" / "openspace-route.js", opencode, opencode_plugin_text)
    return found


# ---------------------------------------------------------------- commands


def install_runtime(dry: bool) -> list[str]:
    """Copy the router and write the wrapper; both are shared by every host."""
    if not ROUTER_SOURCE.is_file():
        raise RuntimeError(f"router source missing: {ROUTER_SOURCE}")
    lines = []
    for path, text, mode in (
        (ROUTER, ROUTER_SOURCE.read_text(encoding="utf-8"), 0o644),
        (WRAPPER, wrapper_text(), 0o755),
    ):
        existing = read_regular(path)
        if existing is not None and existing[0] == text:
            lines.append(f"unchanged {path}")
        elif dry:
            lines.append(f"would write {path}")
        else:
            atomic_write(path, text, mode)
            lines.append(f"wrote {path}")
    return lines


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("action", choices=("install", "remove", "status"))
    parser.add_argument("--host", action="append", choices=sorted(hosts()), help="limit to these hosts (repeatable)")
    parser.add_argument("--dry-run", action="store_true", help="report the changes without writing")
    args = parser.parse_args(argv)
    table = hosts()
    selected = args.host or sorted(table)
    failed = 0

    if args.action == "install":
        try:
            for line in install_runtime(args.dry_run):
                print(line)
        except Exception as exc:
            print(f"FAILED shared runtime: {exc}", file=sys.stderr)
            return 1
        if not (VENV / "bin" / "python").exists():
            print(f"warning: {VENV}/bin/python is missing; hooks stay silent until install-openspace.sh builds it")

    for name in selected:
        host = table[name]
        try:
            if not host.detected() and args.action != "remove":
                result = "skipped (not installed on this machine)"
            else:
                result = getattr(host, args.action)(args.dry_run) if args.action != "status" else host.status()
                note = host.note() if args.action == "install" and result in ("installed", "would install") else ""
                result += f" - {note}" if note else ""
        except Exception as exc:
            result = f"FAILED: {exc}"
            failed += 1
        print(f"{name:9s} {result}")

    if args.action == "status":
        for path in (WRAPPER, ROUTER):
            print(f"{'present' if path.is_file() else 'missing'}  {path}")
    elif args.action == "remove" and not args.host and not args.dry_run:
        for path in (WRAPPER, ROUTER):
            existing = read_regular(path)
            if existing is not None and (MARKER in existing[0] or ROUTER_SIGNATURE in existing[0]):
                path.unlink()
                print(f"removed {path}")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
