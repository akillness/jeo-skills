#!/usr/bin/env python3
"""Capture assistant outputs on Stop and rtk-compress them into the llm-wiki vault.

Used by ~/.claude/hooks/knowledge-pipeline.sh and delegated from ingest-prompt.py
on turn-end events (Stop / AfterAgent / post-turn). Best-effort only: every error
falls through with exit 0 so the host agent is never blocked.

Lifecycle (ctx): the raw capture is always written; the shared index.md/log.md
rewrite happens under the `vault` layer lock (`ctx.lock.layer_lock`) so it
never interleaves with `ctx gc/checkpoint`. If the lock cannot be acquired
within the wait window the index/log update is deferred (logged to stderr)
and the raw/source/report files still land. `graphify-out/` is checkpoint-only
(regenerated by `ctx checkpoint --scope graphify`); this script never writes it.
"""
from __future__ import annotations

import fcntl
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import time
from contextlib import contextmanager
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Iterator

for _hook_dir in (Path(__file__).resolve().parent, Path.home() / ".agents" / "hooks"):
    if str(_hook_dir) not in sys.path:
        sys.path.insert(0, str(_hook_dir))
try:
    from ctx.lock import Locked, layer_lock  # type: ignore
except Exception:
    class Locked(Exception):  # type: ignore[no-redef]
        def __init__(self, name: str, holder: dict[str, Any] | None = None):
            self.name = name
            self.holder = holder or {}
            super().__init__(f"layer {name!r} is locked")

    @contextmanager
    def layer_lock(name: str, wait_seconds: float = 0) -> Iterator[Path]:  # type: ignore[no-redef]
        path = Path.home() / ".agents" / "hooks" / "ctx" / "locks" / f"{name}.lock"
        path.parent.mkdir(parents=True, exist_ok=True)
        fd = os.open(str(path), os.O_RDWR | os.O_CREAT, 0o644)
        deadline = time.monotonic() + max(0.0, float(wait_seconds))
        try:
            while True:
                try:
                    fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
                    break
                except (BlockingIOError, OSError):
                    if time.monotonic() >= deadline:
                        raise Locked(name)
                    time.sleep(0.1)
            try:
                yield path
            finally:
                try:
                    fcntl.flock(fd, fcntl.LOCK_UN)
                except OSError:
                    pass
        finally:
            os.close(fd)

HOME = Path.home()


def _env_path(name: str) -> Path | None:
    raw = (os.environ.get(name) or "").strip()
    return Path(raw).expanduser() if raw else None


def git_toplevel() -> Path | None:
    try:
        out = subprocess.run(
            ["git", "rev-parse", "--show-toplevel"],
            capture_output=True,
            text=True,
            timeout=5,
        )
    except Exception:
        return None
    if out.returncode != 0:
        return None
    top = out.stdout.strip()
    return Path(top) if top else None


def resolve_vault_root() -> Path:
    explicit = _env_path("LLM_WIKI_VAULT")
    if explicit:
        return explicit
    om_explicit = _env_path("OBSIDIAN_MIND_VAULT")
    if om_explicit:
        return om_explicit / "llm-wiki"
    canonical = HOME / "vaults" / "llm-wiki"
    if canonical.is_dir():
        return canonical
    top = git_toplevel()
    if top:
        return top / "llm-wiki"
    return HOME / "vaults" / "obsidian-mind" / "llm-wiki"


VAULT_ROOT = resolve_vault_root()
STATE_FILE = VAULT_ROOT / ".state" / "ingest-output.json"
RTK_BIN = os.environ.get("RTK_BIN", "rtk")
MAX_TITLE = 64
IGNORE_TITLES = {"", "ok", "okay", "done"}
VAULT_LOCK_WAIT = float(os.environ.get("CTX_VAULT_LOCK_WAIT", "1.0"))
AUTO_END = "<!-- ctx:auto:END -->"


def now_utc() -> datetime:
    frozen = os.environ.get("JEO_INGEST_FROZEN_UTC", "").strip()
    if frozen:
        return datetime.fromisoformat(frozen)
    return datetime.now(timezone.utc)


def read_payload() -> dict[str, Any]:
    raw = ""
    if len(sys.argv) > 1:
        raw = sys.argv[1]
    elif not sys.stdin.isatty():
        raw = sys.stdin.read()
    raw = raw.strip()
    if not raw:
        return {}
    try:
        return json.loads(raw)
    except json.JSONDecodeError:
        return {"raw": raw}


def load_state() -> dict[str, Any]:
    if not STATE_FILE.exists():
        return {}
    try:
        return json.loads(STATE_FILE.read_text(encoding="utf-8"))
    except Exception:
        return {}


def save_state(state: dict[str, Any]) -> None:
    STATE_FILE.parent.mkdir(parents=True, exist_ok=True)
    STATE_FILE.write_text(json.dumps(state, indent=2, ensure_ascii=False), encoding="utf-8")


def ensure_vault() -> None:
    for rel in [
        "raw/sources/outputs",
        "wiki/sources",
        "wiki/reports",
        ".state",
    ]:
        (VAULT_ROOT / rel).mkdir(parents=True, exist_ok=True)


def flatten_text(value: Any) -> list[str]:
    out: list[str] = []
    if isinstance(value, str):
        out.append(value)
    elif isinstance(value, list):
        for item in value:
            out.extend(flatten_text(item))
    elif isinstance(value, dict):
        block_type = value.get("type")
        if block_type == "text" and isinstance(value.get("text"), str):
            out.append(value["text"])
        elif block_type is None:
            if isinstance(value.get("text"), str):
                out.append(value["text"])
            elif "content" in value:
                out.extend(flatten_text(value["content"]))
    return out


def extract_session_id(payload: dict[str, Any]) -> str:
    for key in ("session_id", "sessionId", "resourceId", "resource_id", "thread_id"):
        value = payload.get(key)
        if isinstance(value, str) and value:
            return value[:32]
    return "session"


def transcript_path(payload: dict[str, Any]) -> Path | None:
    for key in ("transcript_path", "transcriptPath", "conversation_path", "conversationPath"):
        value = payload.get(key)
        if isinstance(value, str) and value:
            path = Path(value).expanduser()
            if path.exists():
                return path
    return None


def extract_last_assistant_output(payload: dict[str, Any]) -> str:
    # Direct payload fallback for non-Claude runtimes or tests.
    for key in ("assistant_output", "output", "response", "text", "raw"):
        value = payload.get(key)
        if isinstance(value, str) and value.strip():
            return value.strip()

    path = transcript_path(payload)
    if not path:
        return ""

    last = ""
    try:
        with path.open(encoding="utf-8") as handle:
            for line in handle:
                line = line.strip()
                if not line:
                    continue
                try:
                    entry = json.loads(line)
                except json.JSONDecodeError:
                    continue
                if entry.get("type") != "assistant":
                    continue
                message = entry.get("message")
                if isinstance(message, dict):
                    parts = flatten_text(message.get("content", []))
                else:
                    parts = flatten_text(entry.get("content", []))
                text = "\n\n".join(part.strip() for part in parts if part and part.strip()).strip()
                if text:
                    last = text
    except Exception:
        return ""
    return last


def compress_text(text: str) -> tuple[str, dict[str, Any]]:
    original = text
    method = "local"
    compacted = text
    rtk_path = shutil.which(RTK_BIN)
    if rtk_path:
        try:
            result = subprocess.run(
                [rtk_path, "pipe"],
                input=text,
                capture_output=True,
                text=True,
                timeout=15,
            )
            if result.returncode == 0 and result.stdout.strip():
                compacted = result.stdout
                method = "rtk"
        except Exception:
            compacted = text
            method = "local"
    lines = [line.rstrip() for line in compacted.replace("\r\n", "\n").split("\n")]
    collapsed: list[str] = []
    blank_run = 0
    for line in lines:
        if line == "":
            blank_run += 1
            if blank_run > 1:
                continue
        else:
            blank_run = 0
        collapsed.append(line)
    compressed = "\n".join(collapsed).strip() or original.strip()
    orig_chars = len(original)
    saved = orig_chars - len(compressed)
    return compressed, {
        "method": method,
        "original_chars": orig_chars,
        "compressed_chars": len(compressed),
        "saved_chars": saved if saved > 0 else 0,
        "saved_pct": round(100 * saved / orig_chars, 1) if orig_chars and saved > 0 else 0.0,
    }


def slugify(text: str, max_len: int = 48) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    slug = re.sub(r"-{2,}", "-", slug)
    return (slug or "assistant-output")[:max_len].strip("-") or "assistant-output"


def title_for(text: str) -> str:
    first = next((line.strip("# -*\t ") for line in text.splitlines() if line.strip()), "assistant output")
    if len(first) > MAX_TITLE:
        first = first[: MAX_TITLE - 1].rstrip() + "…"
    return first or "assistant output"


def fenced_block(text: str, info: str = "text") -> str:
    longest = max((len(m.group(0)) for m in re.finditer(r"`+", text)), default=0)
    delim = "`" * max(3, longest + 1)
    return f"{delim}{info}\n{text}\n{delim}"


def insert_marker_line(file_path: Path, marker: str, line: str) -> None:
    """Insert `line` before `<!-- MARKER:END -->`; else before the ctx:auto END
    marker (so auto bullets stay inside the ctx-managed block); else create the
    marker block at EOF. Rewrites via temp+rename."""
    anchor = f"<!-- {marker}:END -->"
    text = file_path.read_text(encoding="utf-8") if file_path.exists() else ""
    if line in text:
        return
    if anchor in text:
        text = text.replace(anchor, f"{line}\n{anchor}", 1)
    elif AUTO_END in text:
        text = text.replace(AUTO_END, f"{line}\n{AUTO_END}", 1)
    else:
        text = text.rstrip() + f"\n\n## {marker.title()}\n<!-- {marker}:START -->\n{line}\n<!-- {marker}:END -->\n"
    atomic_write(file_path, text)


def atomic_write(file_path: Path, text: str) -> None:
    tmp = file_path.with_name(f".{file_path.name}.{os.getpid()}.tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, file_path)


def append_log(title: str, body_lines: list[str]) -> None:
    log_path = VAULT_ROOT / "log.md"
    stamp = now_utc()
    with log_path.open("a", encoding="utf-8") as handle:
        handle.write(f"\n## {stamp.strftime('%Y-%m-%d %H:%M:%S UTC')} — {title}\n")
        for line in body_lines:
            handle.write(line + "\n")


def is_duplicate(session_id: str, output_text: str) -> bool:
    digest = hashlib.sha256(f"{session_id}\n{output_text}".encode("utf-8")).hexdigest()
    key = session_id or "default"
    state = load_state()
    sessions = state.get("sessions") if isinstance(state.get("sessions"), dict) else {}
    return sessions.get(key) == digest


def record_dedupe(session_id: str, output_text: str) -> None:
    digest = hashlib.sha256(f"{session_id}\n{output_text}".encode("utf-8")).hexdigest()
    key = session_id or "default"
    state = load_state()
    sessions = state.get("sessions") if isinstance(state.get("sessions"), dict) else {}
    sessions[key] = digest
    save_state({"last_digest": digest, "updated_at": now_utc().isoformat(), "session_id": session_id, "sessions": sessions})


def defer_index_update(reason: str, title: str, **paths: str) -> None:
    """The vault lock was busy: raw/source/report are already on disk; record the
    deferred index/log bullets so the next ingest or `ctx refresh` reconciles."""
    try:
        note = VAULT_ROOT / ".state" / "deferred-index.jsonl"
        note.parent.mkdir(parents=True, exist_ok=True)
        entry = {"at": now_utc().isoformat(), "script": "ingest-output", "title": title, "reason": reason, **paths}
        with note.open("a", encoding="utf-8") as handle:
            handle.write(json.dumps(entry, ensure_ascii=False) + "\n")
    except Exception:
        pass
    sys.stderr.write(f"ingest-output: index/log update deferred ({reason})\n")


def reconcile_deferred_index() -> None:
    note = VAULT_ROOT / ".state" / "deferred-index.jsonl"
    if not note.is_file():
        return
    try:
        lines = [line.strip() for line in note.read_text(encoding="utf-8").splitlines() if line.strip()]
        note.unlink(missing_ok=True)
        for line in lines:
            item = json.loads(line)
            title = item.get("title", "Deferred Capture")
            if item.get("source"):
                insert_marker_line(VAULT_ROOT / "index.md", "SOURCES", f"- [[{item['source']}]] - {title}")
            if item.get("query"):
                insert_marker_line(VAULT_ROOT / "index.md", "QUERIES", f"- [[{item['query']}]] - {title}")
            if item.get("report"):
                insert_marker_line(VAULT_ROOT / "index.md", "REPORTS", f"- [[{item['report']}]] - {title}")
    except Exception:
        pass

def _write_exclusive(path: Path, content: str, *, encoding: str = "utf-8") -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("x", encoding=encoding) as handle:
        handle.write(content)


def write_output_files(output_text: str, session_id: str) -> None:
    stamp = now_utc()
    date_slug = stamp.strftime("%Y-%m-%d")
    time_slug = stamp.strftime("%H%M%S")
    session_short = slugify(session_id or "session", max_len=12)
    title = title_for(output_text)
    slug = slugify(title)
    compressed, cmeta = compress_text(output_text)
    base_id = hashlib.sha256(f"{session_id}\n{output_text}".encode("utf-8")).hexdigest()[:8]

    raw_dir = VAULT_ROOT / "raw" / "sources" / "outputs" / stamp.strftime("%Y") / stamp.strftime("%m") / stamp.strftime("%d")
    raw_dir.mkdir(parents=True, exist_ok=True)
    for attempt in range(100):
        capture_id = base_id if attempt == 0 else f"{base_id}-{attempt}"
        raw_path = raw_dir / f"{time_slug}-{session_short}-{capture_id}-{slug}.md"
        source_rel = Path("wiki") / "sources" / f"{date_slug}-{time_slug}-{capture_id}-{slug}-output.md"
        source_path = VAULT_ROOT / source_rel
        report_rel = Path("wiki") / "reports" / f"{date_slug}-{time_slug}-{capture_id}-{slug}-answer.md"
        report_path = VAULT_ROOT / report_rel
        if not raw_path.exists() and not source_path.exists() and not report_path.exists():
            break

    _write_exclusive(
        raw_path,
        "\n".join([
            "---",
            'type: "assistant-output"',
            f'session_id: "{session_id}"',
            f'captured_at: "{stamp.isoformat()}"',
            f'report: "[[{report_rel.with_suffix("").as_posix()}]]"',
            "---",
            "",
            f"# {title}",
            "",
            "## Output",
            "",
            fenced_block(output_text),
            "",
        ]),
        encoding="utf-8",
    )

    summary_lines = [
        "---",
        'type: "source-summary"',
        'source_type: "assistant-output"',
        f'captured_at: "{stamp.isoformat()}"',
        f'raw_path: "{raw_path.relative_to(VAULT_ROOT).as_posix()}"',
        f'session_id: "{session_id}"',
        f'rtk_method: "{cmeta["method"]}"',
        f'rtk_original_chars: {cmeta["original_chars"]}',
        f'rtk_compressed_chars: {cmeta["compressed_chars"]}',
        f'rtk_saved_pct: {cmeta["saved_pct"]}',
        "---",
        "",
        f"# {title}",
        "",
        f"- Raw output: [[{raw_path.relative_to(VAULT_ROOT).with_suffix('').as_posix()}]]",
        f"- Filed report: [[{report_rel.with_suffix('').as_posix()}]]",
        f"- rtk compression: {cmeta['method']} ({cmeta['original_chars']}→{cmeta['compressed_chars']} chars, -{cmeta['saved_pct']}%)",
        "",
        "## Compressed Output (rtk)",
        "",
        fenced_block(compressed[:3000]),
        "",
    ]
    _write_exclusive(source_path, "\n".join(summary_lines), encoding="utf-8")

    _write_exclusive(
        report_path,
        "\n".join([
            "---",
            f'title: "{title}"',
            f'created_at: "{stamp.isoformat()}"',
            'section: "reports"',
            'status: "captured"',
            f'session_id: "{session_id}"',
            f'raw_output: "[[{raw_path.relative_to(VAULT_ROOT).with_suffix("").as_posix()}]]"',
            f'source_summary: "[[{source_rel.with_suffix("").as_posix()}]]"',
            "---",
            "",
            f"# {title}",
            "",
            "## Answer Output (rtk-compressed)",
            "",
            compressed,
            "",
            "## Evidence and Citations",
            "",
            f"- [[{source_rel.with_suffix('').as_posix()}]]",
            f"- [[{raw_path.relative_to(VAULT_ROOT).with_suffix('').as_posix()}]]",
            "",
        ]),
        encoding="utf-8",
    )

    try:
        with layer_lock("vault", wait_seconds=VAULT_LOCK_WAIT):
            reconcile_deferred_index()
            insert_marker_line(VAULT_ROOT / "index.md", "SOURCES", f"- [[{source_rel.with_suffix('').as_posix()}]] - {title}")
            insert_marker_line(VAULT_ROOT / "index.md", "REPORTS", f"- [[{report_rel.with_suffix('').as_posix()}]] - {title}")
            append_log(
                title,
                [
                    f"- Raw output: [[{raw_path.relative_to(VAULT_ROOT).with_suffix('').as_posix()}]]",
                    f"- Source note: [[{source_rel.with_suffix('').as_posix()}]]",
                    f"- Report note: [[{report_rel.with_suffix('').as_posix()}]]",
                    f"- rtk compression: {cmeta['method']} ({cmeta['original_chars']}→{cmeta['compressed_chars']} chars, -{cmeta['saved_pct']}%)",
                ],
            )
    except Locked as exc:
        defer_index_update(
            str(exc),
            title,
            raw=raw_path.relative_to(VAULT_ROOT).with_suffix("").as_posix(),
            source=source_rel.with_suffix("").as_posix(),
            report=report_rel.with_suffix("").as_posix(),
        )


def ingest_output_payload(payload: dict[str, Any]) -> int:
    try:
        session_id = extract_session_id(payload)
        output_text = extract_last_assistant_output(payload)
        if not output_text or title_for(output_text).lower() in IGNORE_TITLES:
            return 0
        ensure_vault()
        if is_duplicate(session_id, output_text):
            return 0
        write_output_files(output_text, session_id)
        record_dedupe(session_id, output_text)
    except Exception:
        pass
    return 0


def main() -> int:
    try:
        payload = read_payload()
        return ingest_output_payload(payload)
    except Exception:
        pass
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
